// Builds the iPhone Shortcut script from the extension's Google adapter.
// Usage: node scripts/build-mobile.js  (writes mobile/google-ai-export.js)
import { readFileSync, writeFileSync } from "node:fs";
import { VERSION } from "../src/appConfig.js";

export function buildMobileScript() {
  const adapter = readFileSync(new URL("../chrome-extension/browserAdapters.js", import.meta.url), "utf8");
  const runner = readFileSync(new URL("../mobile/googleAiRunner.js", import.meta.url), "utf8")
    .replace("__EXPORTER_VERSION__", JSON.stringify(VERSION));
  return `// AI Chat Exporter ${VERSION}: Google AI export for iPhone Shortcuts. Generated by scripts/build-mobile.js.\n${adapter}\n${runner}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../mobile/google-ai-export.js", import.meta.url), buildMobileScript());
  console.log("Wrote mobile/google-ai-export.js");
}
